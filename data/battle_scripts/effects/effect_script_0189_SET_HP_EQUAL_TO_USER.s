#include "config.h"
#include "constants/battle_constants.h"
.include "battle_commands.inc"

.data

_Start:
    UpdateMonDataFromVar OPCODE_GET, BATTLER_CATEGORY_DEFENDER, BMON_DATA_HP, BSCRIPT_VAR_DAMAGE
    UpdateMonDataFromVar OPCODE_GET, BATTLER_CATEGORY_ATTACKER, BMON_DATA_HP, BSCRIPT_VAR_CALC_TEMP
    CompareVarToVar OPCODE_LTE, BSCRIPT_VAR_DAMAGE, BSCRIPT_VAR_CALC_TEMP, _MoveFailed
    UpdateVarFromVar OPCODE_SUB, BSCRIPT_VAR_DAMAGE, BSCRIPT_VAR_CALC_TEMP
    UpdateVar OPCODE_MUL, BSCRIPT_VAR_DAMAGE, -1
    UpdateVar OPCODE_FLAG_ON, BSCRIPT_VAR_BATTLE_STATUS, BATTLE_STATUS_IGNORE_TYPE_EFFECTIVENESS
#ifdef TOTEM_FIXED_DAMAGE_REDUCTION
    CompareVarToValue OPCODE_FLAG_NOT, BSCRIPT_VAR_BATTLE_TYPE, BATTLE_TYPE_TOTEM, _End
    GoToIfTotem BATTLER_CATEGORY_DEFENDER, _HandleTotem
#endif

_End:
    End 

_MoveFailed:
    UpdateVar OPCODE_FLAG_ON, BSCRIPT_VAR_MOVE_STATUS_FLAGS, MOVE_STATUS_FAILED
    End 

// Cap damage at 1/4 enemy max HP.
_HandleTotem:
    UpdateMonDataFromVar OPCODE_GET, BATTLER_CATEGORY_DEFENDER, BMON_DATA_MAXHP, BSCRIPT_VAR_CALC_TEMP
    UpdateVar OPCODE_DIV, BSCRIPT_VAR_CALC_TEMP, 4
    UpdateVar OPCODE_MUL, BSCRIPT_VAR_CALC_TEMP, -1
    CompareVarToVar OPCODE_LTE, BSCRIPT_VAR_DAMAGE, BSCRIPT_VAR_CALC_TEMP, _End
    UpdateVarFromVar OPCODE_SET, BSCRIPT_VAR_DAMAGE, BSCRIPT_VAR_CALC_TEMP
    End
    